func rootCAs() *x509.CertPool {
	pool, err := x509.SystemCertPool()
	if err != nil || pool == nil {
		pool = x509.NewCertPool()
	}
	pool.AppendCertsFromPEM([]byte(isrgRootX1))
	for _, path := range extraCertFiles() {
		pem, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		pool.AppendCertsFromPEM(pem)
	}
	return pool
}

// extraCertFiles are CA bundles Go's Linux lookup never searches.
// Termux keeps its bundle under $PREFIX, and a non-login shell may not export PREFIX.
func extraCertFiles() []string {
	var paths []string
	if prefix := os.Getenv("PREFIX"); prefix != "" {
		paths = append(paths,
			filepath.Join(prefix, "etc/tls/cert.pem"),
			filepath.Join(prefix, "etc/ssl/certs/ca-certificates.crt"),
		)
	}
	paths = append(paths, "/data/data/com.termux/files/usr/etc/tls/cert.pem")
	return paths
}
